CREATE TABLE team_invitation (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id      BIGINT      NOT NULL,
  invitee_id   BIGINT      NOT NULL,
  status       VARCHAR(20) NOT NULL DEFAULT 'PENDING'
               CONSTRAINT ck_ti_status CHECK (status IN ('PENDING','ACCEPTED','DECLINED')),
  created_at   TIMESTAMP   NOT NULL,
  responded_at TIMESTAMP   NULL,
  CONSTRAINT fk_ti_team    FOREIGN KEY (team_id)    REFERENCES team(id),
  CONSTRAINT fk_ti_invitee FOREIGN KEY (invitee_id) REFERENCES member(id)
);
CREATE INDEX idx_ti_invitee ON team_invitation (invitee_id, status);

CREATE TABLE exemption_period (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  week_start DATE         NOT NULL UNIQUE,
  reason     VARCHAR(200) NOT NULL,
  created_by BIGINT       NOT NULL,
  created_at TIMESTAMP    NOT NULL,
  updated_at TIMESTAMP    NULL,
  CONSTRAINT fk_ep_admin FOREIGN KEY (created_by) REFERENCES member(id)
);

CREATE TABLE personal_exemption (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id     BIGINT       NOT NULL,
  requested_by  BIGINT       NOT NULL,
  week_start    DATE         NOT NULL,
  status        VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
                CONSTRAINT ck_pe_status CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  reason        VARCHAR(500) NOT NULL,
  reject_reason VARCHAR(500) NULL,
  responded_at  TIMESTAMP    NULL,
  created_at    TIMESTAMP    NOT NULL,
  CONSTRAINT fk_pe_member    FOREIGN KEY (member_id)    REFERENCES member(id),
  CONSTRAINT fk_pe_requester FOREIGN KEY (requested_by) REFERENCES member(id)
);
CREATE INDEX idx_pe_pending ON personal_exemption (status, week_start);
CREATE INDEX idx_pe_member  ON personal_exemption (member_id, week_start);

CREATE TABLE judgment_correction (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  judgment_id   BIGINT       NOT NULL,
  before_status VARCHAR(20)  NOT NULL
                CONSTRAINT ck_jc_before CHECK (before_status IN ('PASS','FAIL','EXEMPT','EXCLUDED','HOLD')),
  after_status  VARCHAR(20)  NOT NULL
                CONSTRAINT ck_jc_after CHECK (after_status IN ('PASS','FAIL','EXEMPT')),
  reason        VARCHAR(500) NOT NULL,
  admin_id      BIGINT       NOT NULL,
  created_at    TIMESTAMP    NOT NULL,
  CONSTRAINT fk_jc_judgment FOREIGN KEY (judgment_id) REFERENCES weekly_judgment(id),
  CONSTRAINT fk_jc_admin    FOREIGN KEY (admin_id)    REFERENCES member(id)
);
CREATE INDEX idx_jc_judgment ON judgment_correction (judgment_id);

CREATE TABLE notice (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title      VARCHAR(200) NOT NULL,
  content    TEXT         NOT NULL,
  is_pinned  BOOLEAN      NOT NULL DEFAULT FALSE,
  is_system  BOOLEAN      NOT NULL DEFAULT FALSE,
  author_id  BIGINT       NOT NULL,
  created_at TIMESTAMP    NOT NULL,
  updated_at TIMESTAMP    NULL,
  CONSTRAINT fk_notice_author FOREIGN KEY (author_id) REFERENCES member(id)
);
CREATE INDEX idx_notice_list ON notice (is_pinned DESC, created_at DESC);

CREATE TABLE admin_action_log (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id    BIGINT       NOT NULL,
  action      VARCHAR(30)  NOT NULL
              CONSTRAINT ck_aal_action CHECK (action IN ('REJECT_MEMBER','DELETE_POST','DELETE_COMMENT',
                                                         'FULFILL_PENALTY','CORRECT_JUDGMENT','RESTORE_WARNING')),
  target_type VARCHAR(30)  NOT NULL,
  target_id   VARCHAR(40)  NOT NULL,
  reason      VARCHAR(500) NULL,
  created_at  TIMESTAMP    NOT NULL,
  CONSTRAINT fk_aal_admin FOREIGN KEY (admin_id) REFERENCES member(id)
);
CREATE INDEX idx_aal_admin ON admin_action_log (admin_id, created_at);
