-- V1__init.sql (PostgreSQL)
-- 열거 값은 VARCHAR + CHECK로 둔다. 시각은 KST 기준 TIMESTAMP(시간대 없음)
CREATE TABLE member (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  github_id            BIGINT       NOT NULL UNIQUE,
  github_login         VARCHAR(39)  NOT NULL,
  nickname             VARCHAR(30)  NOT NULL,
  profile_image_url    VARCHAR(512) NULL,
  status               VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
                       CONSTRAINT ck_member_status CHECK (status IN ('PENDING','ACTIVE','REJECTED')),
  role                 VARCHAR(20)  NOT NULL DEFAULT 'MEMBER'
                       CONSTRAINT ck_member_role CHECK (role IN ('MEMBER','ADMIN')),
  first_team_joined_at TIMESTAMP    NULL,
  created_at           TIMESTAMP    NOT NULL,
  approved_at          TIMESTAMP    NULL
);
CREATE INDEX idx_member_login ON member (github_login);

CREATE TABLE team (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(50)  NOT NULL,
  description VARCHAR(200) NULL,
  leader_id   BIGINT       NOT NULL,
  invite_code VARCHAR(255) NOT NULL UNIQUE,
  is_public   BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMP    NOT NULL,
  deleted_at  TIMESTAMP    NULL,
  CONSTRAINT fk_team_leader FOREIGN KEY (leader_id) REFERENCES member(id)
);

CREATE TABLE team_member (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id          BIGINT       NOT NULL,
  member_id        BIGINT       NOT NULL,
  joined_at        TIMESTAMP    NOT NULL,
  left_at          TIMESTAMP    NULL,
  leave_type       VARCHAR(20)  NULL
                   CONSTRAINT ck_tm_leave_type CHECK (leave_type IN ('SELF','KICKED','TEAM_DELETED')),
  joined_by        VARCHAR(20)  NOT NULL
                   CONSTRAINT ck_tm_joined_by CHECK (joined_by IN ('INVITE_CODE','INVITATION')),
  used_invite_code VARCHAR(255) NULL,
  CONSTRAINT uk_team_member UNIQUE (team_id, member_id, joined_at),
  CONSTRAINT fk_tm_team   FOREIGN KEY (team_id)   REFERENCES team(id),
  CONSTRAINT fk_tm_member FOREIGN KEY (member_id) REFERENCES member(id)
);
CREATE INDEX idx_member_current ON team_member (member_id, left_at);

CREATE TABLE post_index (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mongo_post_id CHAR(24)    NOT NULL UNIQUE,
  author_id     BIGINT      NOT NULL,
  team_id       BIGINT      NULL,
  post_type     VARCHAR(20) NOT NULL
                CONSTRAINT ck_pi_post_type CHECK (post_type IN ('TROUBLESHOOTING','DEVLOG')),
  is_record     BOOLEAN     NOT NULL,
  written_date  DATE        NOT NULL,
  created_at    TIMESTAMP   NOT NULL,
  deleted_at    TIMESTAMP   NULL,
  CONSTRAINT fk_pi_author FOREIGN KEY (author_id) REFERENCES member(id)
);
CREATE INDEX idx_post_judge ON post_index (author_id, written_date, is_record);

CREATE TABLE weekly_judgment (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id      BIGINT      NOT NULL,
  week_start     DATE        NOT NULL,
  status         VARCHAR(20) NOT NULL
                 CONSTRAINT ck_wj_status CHECK (status IN ('PASS','FAIL','EXEMPT','EXCLUDED','HOLD')),
  skip_reason    VARCHAR(30) NULL
                 CONSTRAINT ck_wj_skip_reason
                 CHECK (skip_reason IN ('NO_TEAM','FIRST_WEEK','EXEMPTION_PERIOD','PERSONAL_EXEMPTION')),
  hold_reason    VARCHAR(30) NULL
                 CONSTRAINT ck_wj_hold_reason CHECK (hold_reason IN ('API_ERROR','IDENTITY_MISMATCH')),
  retry_count    INT         NOT NULL DEFAULT 0,
  verified_days  INT         NULL,
  record_count   INT         NULL,
  corrected      BOOLEAN     NOT NULL DEFAULT FALSE,
  judged_at      TIMESTAMP   NULL,
  CONSTRAINT uk_judgment UNIQUE (member_id, week_start),
  CONSTRAINT fk_wj_member FOREIGN KEY (member_id) REFERENCES member(id)
);
CREATE INDEX idx_judgment_status ON weekly_judgment (status, week_start);

CREATE TABLE judgment_team (
  judgment_id BIGINT NOT NULL,
  team_id     BIGINT NOT NULL,
  PRIMARY KEY (judgment_id, team_id),
  CONSTRAINT fk_jt_judgment FOREIGN KEY (judgment_id) REFERENCES weekly_judgment(id),
  CONSTRAINT fk_jt_team     FOREIGN KEY (team_id)     REFERENCES team(id)
);

CREATE TABLE judgment_day (
  judgment_id BIGINT  NOT NULL,
  day         DATE    NOT NULL,
  has_grass   BOOLEAN NOT NULL,
  has_record  BOOLEAN NOT NULL,
  PRIMARY KEY (judgment_id, day),
  CONSTRAINT fk_jd_judgment FOREIGN KEY (judgment_id) REFERENCES weekly_judgment(id)
);

CREATE TABLE warning (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id     BIGINT      NOT NULL,
  week_start    DATE        NOT NULL,
  deleted_at    TIMESTAMP   NULL,
  delete_reason VARCHAR(20) NULL
                CONSTRAINT ck_w_delete_reason CHECK (delete_reason IN ('KICKED','TEAM_DELETED')),
  created_at    TIMESTAMP   NOT NULL,
  CONSTRAINT uk_warning UNIQUE (member_id, week_start),
  CONSTRAINT fk_w_member FOREIGN KEY (member_id) REFERENCES member(id)
);
CREATE INDEX idx_warning_alive ON warning (member_id, deleted_at);

CREATE TABLE warning_team (
  warning_id BIGINT    NOT NULL,
  team_id    BIGINT    NOT NULL,
  removed_at TIMESTAMP NULL,
  PRIMARY KEY (warning_id, team_id),
  CONSTRAINT fk_wt_warning FOREIGN KEY (warning_id) REFERENCES warning(id),
  CONSTRAINT fk_wt_team    FOREIGN KEY (team_id)    REFERENCES team(id)
);

CREATE TABLE penalty_fulfillment (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id    BIGINT    NOT NULL,
  fulfilled_at TIMESTAMP NOT NULL,
  admin_id     BIGINT    NOT NULL,
  reached_week DATE      NOT NULL,
  CONSTRAINT fk_pf_member FOREIGN KEY (member_id) REFERENCES member(id),
  CONSTRAINT fk_pf_admin  FOREIGN KEY (admin_id)  REFERENCES member(id)
);
CREATE INDEX idx_pf_member ON penalty_fulfillment (member_id, fulfilled_at);
